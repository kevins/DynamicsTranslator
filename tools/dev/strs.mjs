import { readFileSync } from 'node:fs';
import { deflateRawSync } from 'node:zlib';
import ts from 'typescript';
const c = readFileSync(process.argv[2] || 'dist/translator.min.js', 'utf8');
const sf = ts.createSourceFile('x.js', c, ts.ScriptTarget.Latest, false, ts.ScriptKind.JS);
const out = [];
const K = ts.SyntaxKind;
(function walk(n) { if ([K.StringLiteral, K.NoSubstitutionTemplateLiteral, K.TemplateHead, K.TemplateMiddle, K.TemplateTail].includes(n.kind)) out.push(n.text); ts.forEachChild(n, walk); })(sf);
const D = (s) => deflateRawSync(Buffer.from(s), { level: 9 }).length;
const css = out.filter((s) => s.length > 1500);
const text = out.filter((s) => s.length <= 1500 && /[a-z] [a-z]/i.test(s) && !/^[\w.-]+( [\w.-]+)*$/.test(s) || (s.length > 25 && / /.test(s) && s.length <= 1500));
const svg = out.filter((s) => /^M[\d.\s-]/.test(s) || /^[Mm]\d/.test(s));
const all = out.join('\u0000');
console.log('strings', out.length, 'chars', all.length, 'deflate', D(all));
console.log('css', css.length, css.reduce((a, s) => a + s.length, 0), 'deflate', D(css.join('')));
console.log('svg paths', svg.length, svg.reduce((a, s) => a + s.length, 0), 'deflate', D(svg.join('|')));
console.log('prose-ish', text.length, text.reduce((a, s) => a + s.length, 0), 'deflate', D(text.join('|')));
const code = c.length;
console.log('whole', code, D(c));
if (process.argv[3]) console.log(text.sort((a, b) => b.length - a.length).slice(0, +process.argv[3]).join('\n'));
